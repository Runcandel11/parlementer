// Parlementer — tes jalur Postgres via pg-mem (emulator Postgres di memori).
// Memverifikasi: skema Postgres dibuat, seed berjalan, placeholder `?`→`$n`
// diterjemahkan dengan benar, RETURNING id bekerja, transaksi commit,
// dan operasi inti (daftar warga, penawaran pasar, pesan chat) berjalan di dialek pg.
// BUKAN pengganti tes terhadap Postgres sungguhan (Neon/Supabase) saat deploy.
//
// BATASAN pg-mem 2.8.1 (terverifikasi empiris, BUKAN bug aplikasi):
//  1. `kolom - $param` dihitung terbalik (jadi `$param - kolom`) — mis. qty 10,
//     `qty - $1` dengan $1=5 menghasilkan -5, bukan 5. SQL aplikasi memakai pola
//     ini (`gold = gold - ?`, `qty = qty - ?`) yang BENAR di Postgres sungguhan
//     (dan terverifikasi lewat tes e2e SQLite). Di tes ini, pengurangan dihitung
//     di JS (`SET qty = ?`) agar tidak kena bug emulator.
//  2. ROLLBACK tidak berfungsi (BEGIN → UPDATE → ROLLBACK tetap tersimpan).
//     Pemeriksaan rollback dilewati di sini; akan diverifikasi di Postgres
//     sungguhan saat deploy. Logika rollback `tx()` sendiri sama untuk kedua dialek.
//  3. `CREATE TABLE IF NOT EXISTS` pada tabel yang SUDAH ADA dan memakai
//     `GENERATED BY DEFAULT AS IDENTITY` gagal di pg-mem pada run kedua
//     ("Not supported ... AST ... not been read"). Di Postgres sungguhan
//     itu no-op yang valid. Sejak perbaikan advisory lock 27 Nov 2026,
//     initDb kedua TIDAK LAGI menjalankan schema() (jalur cepat lewat
//     penanda versi di db_meta), jadi initDb 2× kini BISA diuji di sini
//     (§9); idempotensi + migrasi INTEGER->BIGINT + advisory lock juga
//     diverifikasi terhadap Postgres sungguhan (lihat laporan deploy).
// Jalankan: npm run test:pg
process.env.PG_MEM_TEST = '1';
process.env.JWT_SECRET = 'pg-test-secret';

const { initDb, sql, one, run, tx, closeDb } = await import('../src/db.js');

let passed = 0;
let failed = 0;
function check(name, cond, detail = '') {
  if (cond) { passed++; console.log(`  ✓ ${name}${detail ? ' — ' + detail : ''}`); }
  else { failed++; console.log(`  ✗ ${name}${detail ? ' — ' + detail : ''}`); }
}

console.log('[pg-test] Inisialisasi skema Postgres (pg-mem)...');
await initDb();

console.log('\n[1] Seed statis');
let r = await one('SELECT COUNT(*) AS n FROM regions');
check('17 wilayah ter-seed', Number(r.n) === 17, `n=${r.n}`);
r = await one('SELECT COUNT(*) AS n FROM commodities');
check('15 komoditas ter-seed', Number(r.n) === 15, `n=${r.n}`);
r = await one('SELECT COUNT(*) AS n FROM jobs WHERE is_admin = 1');
check('18 lowongan ADMIN ter-seed (satu per wilayah, Kepri 2)', Number(r.n) === 18, `n=${r.n}`);
r = await one('SELECT COUNT(DISTINCT region_id) AS n FROM jobs WHERE is_admin = 1');
check('Lowongan ADMIN ada di semua 17 wilayah', Number(r.n) === 17, `n=${r.n}`);
r = await one('SELECT COUNT(*) AS n FROM country');
check('0 negara di awal (redesain dunia — dunia terpecah)', Number(r.n) === 0, `n=${r.n}`);
r = await one("SELECT COUNT(*) AS n FROM market_offers");
check('Pasar mulai 0 penawaran', Number(r.n) === 0);
r = await one('SELECT COUNT(*) AS n FROM citizens');
check('0 warga (tanpa bot)', Number(r.n) === 0);

console.log('\n[2] Tulis/baca dengan placeholder multi-param + RETURNING id');
const now = Date.now();
const user = await run(
  'INSERT INTO users (email, username, pass_hash, referred_by, created_at) VALUES (?,?,?,?,?) RETURNING id',
  ['pg@test.local', 'warga_pg', 'hash-palsu', null, now]);
check('INSERT user mengembalikan id', typeof user.id === 'number' && user.id > 0, `id=${user.id}`);
const citizen = await run(
  'INSERT INTO citizens (user_id, level, xp, energy, gold, usd, region_id, home_region_id, created_at) VALUES (?,?,?,?,?,?,?,?,?) RETURNING id',
  [user.id, 1, 0, 100, 50, 500, 1, 1, now]);
check('INSERT citizen mengembalikan id', typeof citizen.id === 'number' && citizen.id > 0, `id=${citizen.id}`);
r = await one('SELECT * FROM citizens WHERE user_id = ? AND level = ? AND gold = ?', [user.id, 1, 50]);
check('SELECT 3 placeholder terbaca kembali', !!r && r.usd === 500, `usd=${r?.usd}`);
r = await one('SELECT last_seen_at FROM citizens WHERE id = ?', [citizen.id]);
check('Kolom last_seen_at ada (migrasi online, default 0)', r && r.last_seen_at === 0, `last_seen_at=${r?.last_seen_at}`);
await run('UPDATE citizens SET last_seen_at = ? WHERE id = ?', [now, citizen.id]);
r = await one('SELECT last_seen_at FROM citizens WHERE id = ?', [citizen.id]);
check('last_seen_at bisa ditulis (heartbeat online)', r.last_seen_at === now, `last_seen_at=${r?.last_seen_at}`);

console.log('\n[3] Transaksi: commit (rollback dilewati — lihat catatan pg-mem di atas)');
await tx(async (t) => {
  await t.run('UPDATE citizens SET gold = gold + 5 WHERE id = ?', [citizen.id]);
  await t.run('INSERT INTO notifications (citizen_id, category, title, content, created_at) VALUES (?,?,?,?,?) RETURNING id',
    [citizen.id, 'SISTEM', 'Tes', 'Notifikasi tes', Date.now()]);
});
r = await one('SELECT gold FROM citizens WHERE id = ?', [citizen.id]);
check('Transaksi commit: emas 50 → 55', r.gold === 55, `gold=${r.gold}`);
console.log('  ○ ROLLBACK pg-mem tidak berfungsi — DILEWATI (verifikasi di Postgres sungguhan saat deploy)');

console.log('\n[4] Alur pasar di dialek pg (jual → beli → pajak 2%)');
const com = await one('SELECT id FROM commodities WHERE name = ?', ['Makanan']);
await run('INSERT INTO inventory (citizen_id, commodity_id, tier, qty) VALUES (?,?,?,?) RETURNING id',
  [citizen.id, com.id, 1, 20]);
const offer = await run(
  'INSERT INTO market_offers (seller_id, scope, commodity_id, tier, qty, price, created_at) VALUES (?,?,?,?,?,?,?) RETURNING id',
  [citizen.id, 'local', com.id, 1, 10, 9, Date.now()]);
check('Penawaran jual dibuat', typeof offer.id === 'number', `offerId=${offer.id}`);
const user2 = await run(
  'INSERT INTO users (email, username, pass_hash, referred_by, created_at) VALUES (?,?,?,?,?) RETURNING id',
  ['pg2@test.local', 'warga_pg2', 'hash-palsu', null, now]);
const cit2 = await run(
  'INSERT INTO citizens (user_id, level, xp, energy, gold, usd, region_id, home_region_id, created_at) VALUES (?,?,?,?,?,?,?,?,?) RETURNING id',
  [user2.id, 1, 0, 100, 50, 500, 1, 1, now]);
await tx(async (t) => {
  const o = await t.one('SELECT * FROM market_offers WHERE id = ?', [offer.id]);
  await t.run('UPDATE citizens SET usd = usd - ? WHERE id = ?', [o.price * 5, cit2.id]);
  await t.run('UPDATE citizens SET usd = usd + ? WHERE id = ?', [o.price * 5 * 0.98, citizen.id]);
  // Pengurangan dihitung di JS (hindari bug pg-mem `kolom - $param`); di aplikasi
  // pola `qty = qty - ?` dipakai dan benar di Postgres sungguhan.
  await t.run('UPDATE market_offers SET qty = ? WHERE id = ?', [o.qty - 5, o.id]);
});
const buyer = await one('SELECT usd FROM citizens WHERE id = ?', [cit2.id]);
const seller = await one('SELECT usd FROM citizens WHERE id = ?', [citizen.id]);
check('Pembeli bayar 45 USD (500 → 455)', buyer.usd === 455, `usd=${buyer.usd}`);
check('Penjual terima 44,10 USD (500 → 544,10)', Math.abs(seller.usd - 544.1) < 0.001, `usd=${seller.usd}`);
const left = await one('SELECT qty FROM market_offers WHERE id = ?', [offer.id]);
check('Sisa penawaran 5 unit', left.qty === 5, `qty=${left.qty}`);

console.log('\n[5] Chat & laporan di dialek pg');
const msg = await run(
  'INSERT INTO chat_messages (room, citizen_id, content, article_id, created_at) VALUES (?,?,?,?,?) RETURNING id',
  ['global', citizen.id, 'Halo dunia Parlementer ini tes', null, Date.now()]);
check('Pesan chat tersimpan', typeof msg.id === 'number', `messageId=${msg.id}`);
const msgs = await sql('SELECT * FROM chat_messages WHERE room = ? ORDER BY created_at ASC', ['global']);
check('Pesan terbaca kembali (1 pesan)', msgs.length === 1 && msgs[0].content.includes('Halo dunia'));
await run('INSERT INTO chat_reports (reporter_id, message_id, reason, details, created_at) VALUES (?,?,?,?,?) RETURNING id',
  [cit2.id, msg.id, 'Spam', 'tes laporan', Date.now()]);
const rep = await one('SELECT COUNT(*) AS n FROM chat_reports');
check('Laporan konten tersimpan', Number(rep.n) === 1);

console.log('\n[6] Agregat (dipakai dashboard/pers)');
const agg = await one('SELECT COUNT(*) AS tx, COALESCE(SUM(qty),0) AS units FROM market_tx');
check('Agregat market_tx berjalan (0 transaksi)', Number(agg.tx) === 0);

console.log('\n[7] Banding & avatar di dialek pg');
const ap = await run(
  'INSERT INTO appeals (user_id, ban_reason, text, status, created_at) VALUES (?,?,?,?,?) RETURNING id',
  [user.id, 'cheat', 'Saya tidak memakai cheat, tolong tinjau.', 'menunggu', Date.now()]);
check('Banding dibuat', typeof ap.id === 'number', `appealId=${ap.id}`);
await run(
  'INSERT INTO appeal_messages (appeal_id, sender_id, sender_role, text, created_at) VALUES (?,?,?,?,?) RETURNING id',
  [ap.id, user.id, 'pemain', 'Saya tidak memakai cheat, tolong tinjau.', Date.now()]);
await run(
  'INSERT INTO appeal_messages (appeal_id, sender_id, sender_role, text, created_at) VALUES (?,?,?,?,?) RETURNING id',
  [ap.id, user2.id, 'admin', 'Kami tinjau dulu ya.', Date.now()]);
const apMsgs = await sql('SELECT * FROM appeal_messages WHERE appeal_id = ? ORDER BY created_at ASC', [ap.id]);
check('Thread banding 2 pesan (pemain + admin)', apMsgs.length === 2 && apMsgs[0].sender_role === 'pemain' && apMsgs[1].sender_role === 'admin');
await run('UPDATE appeals SET status = ?, decided_at = ? WHERE id = ?', ['diterima', Date.now(), ap.id]);
const apDone = await one('SELECT status FROM appeals WHERE id = ?', [ap.id]);
check('Banding bisa diputuskan (diterima)', apDone.status === 'diterima');
await run('UPDATE users SET avatar = ? WHERE id = ?', ['data:image/jpeg;base64,/9j/4AAQ', user.id]);
const av = await one('SELECT avatar FROM users WHERE id = ?', [user.id]);
check('Kolom avatar tersimpan di users', av.avatar === 'data:image/jpeg;base64,/9j/4AAQ');
await run('UPDATE users SET avatar = NULL WHERE id = ?', [user.id]);
const av2 = await one('SELECT avatar FROM users WHERE id = ?', [user.id]);
check('Avatar bisa dihapus (NULL)', av2.avatar === null);

console.log('\n[8] Inbox admin: tiket Meja Bantuan & laporan chat di dialek pg');
const tk = await run(
  'INSERT INTO support_tickets (citizen_id, type, topic, details, created_at) VALUES (?,?,?,?,?) RETURNING id',
  [citizen.id, 'Saran', 'Ekonomi & Pasar', 'Saran tes inbox pg.', Date.now()]);
check('Tiket dibuat', typeof tk.id === 'number', `ticketId=${tk.id}`);
const tk0 = await one('SELECT status FROM support_tickets WHERE id = ?', [tk.id]);
check('Status awal tiket "baru"', tk0.status === 'baru', `status=${tk0.status}`);
await run("UPDATE support_tickets SET status = 'dibaca' WHERE id = ?", [tk.id]);
const tk1 = await one('SELECT status FROM support_tickets WHERE id = ?', [tk.id]);
check('Status tiket bisa diubah ke dibaca', tk1.status === 'dibaca');
await run('INSERT INTO chat_reports (reporter_id, message_id, reason, details, created_at) VALUES (?,?,?,?,?) RETURNING id',
  [cit2.id, msg.id, 'Spam', 'tes laporan inbox', Date.now()]);
const rep0 = await one('SELECT status FROM chat_reports WHERE reporter_id = ? ORDER BY id DESC', [cit2.id]);
check('Status awal laporan chat "open"', rep0.status === 'open', `status=${rep0.status}`);
await run("UPDATE chat_reports SET status = 'reviewed' WHERE reporter_id = ?", [cit2.id]);
const rep1 = await one('SELECT status FROM chat_reports WHERE reporter_id = ? ORDER BY id DESC', [cit2.id]);
check('Laporan chat bisa ditandai ditinjau', rep1.status === 'reviewed');

console.log('\n[9] initDb paralel + jalur cepat (perbaikan advisory lock 27 Nov 2026)');
const t0 = Date.now();
await Promise.all(Array.from({ length: 10 }, () => initDb()));
const tPar = Date.now() - t0;
r = await one('SELECT COUNT(*) AS n FROM regions');
check('initDb 10× paralel: seed tetap 17 (tidak terduplikasi)', Number(r.n) === 17, `n=${r.n}, ${tPar}ms`);
const ver = await one("SELECT value FROM db_meta WHERE key = 'schema_version'");
check('Penanda versi skema tersimpan (= 11)', ver?.value === '11', `value=${ver?.value}`);
const t1 = Date.now();
await initDb();
const tFast = Date.now() - t1;
r = await one('SELECT COUNT(*) AS n FROM announcements');
check('initDb kedua (jalur cepat): pengumuman tidak terduplikasi', Number(r.n) <= 2, `n=${r.n}, ${tFast}ms`);
check('initDb paralel 10× selesai cepat (< 10 detik)', tPar < 10000, `${tPar}ms`);
// Fixup data tetap jalan di jalur cepat: user tanpa referral_code (dibuat
// di §2 tanpa kode) harus sudah dibuatkan kode oleh initDb kedua.
const u0 = await one('SELECT referral_code FROM users WHERE email = ?', ['pg@test.local']);
check('Jalur cepat: fixup data tetap jalan (referral_code terisi)', !!u0?.referral_code, `code=${u0?.referral_code}`);

console.log('\n[10] Redesain dunia (27 Nov 2026): dunia terpecah + parlemen 2 Des');
// Semua wilayah merdeka (country_id NULL, kolom warisan country kosong).
r = await one('SELECT COUNT(*) AS n FROM regions WHERE country_id IS NULL');
check('Semua 17 wilayah merdeka (country_id NULL)', Number(r.n) === 17, `n=${r.n}`);
r = await one("SELECT COUNT(*) AS n FROM regions WHERE country <> ''");
check("Kolom warisan regions.country kosong di semua wilayah", Number(r.n) === 0, `n=${r.n}`);
// Tanggal buka parlemen tersimpan di db_meta ≈ 2 Des 2026 00:00 WIB.
const po = await one("SELECT value FROM db_meta WHERE key = 'parliament_opens_at'");
const opensAt = Number(po?.value);
check('parliament_opens_at tersimpan di db_meta', Number.isFinite(opensAt) && opensAt > 0, `value=${po?.value}`);
check('parliament_opens_at = 2 Des 2026 00:00 WIB', opensAt === Date.parse('2026-12-02T00:00:00+07:00'), `value=${opensAt}`);
// Tabel baru ada.
for (const t of ['party_seats', 'country_joins', 'country_join_votes']) {
  r = await one("SELECT COUNT(*) AS n FROM information_schema.tables WHERE table_name = ?", [t]).catch(() => null);
  const exists = r ? Number(r.n) === 1 : false;
  // pg-mem tidak selalu punya information_schema — fallback: query langsung.
  if (!exists) {
    try { await one(`SELECT COUNT(*) AS n FROM ${t}`); check(`Tabel ${t} ada`, true); }
    catch { check(`Tabel ${t} ada`, false); }
  } else check(`Tabel ${t} ada`, true);
}
// CHECK ideologi + sistem negara menolak nilai di luar daftar.
let badIdeology = false;
try { await run("INSERT INTO country (name, ideology, system, capital, founded) VALUES ('Negara Tes','Anarkisme','presidensial','Jakarta','2026-11-27') RETURNING id"); }
catch { badIdeology = true; }
check('Ideologi di luar daftar ditolak CHECK', badIdeology);
let badSystem = false;
try { await run("INSERT INTO country (name, ideology, system, capital, founded) VALUES ('Negara Tes 2','Konservatisme','monarki','Jakarta','2026-11-27') RETURNING id"); }
catch { badSystem = true; }
check('Sistem di luar daftar ditolak CHECK', badSystem);
const okCountry = await run("INSERT INTO country (name, ideology, system, capital, founded) VALUES ('Negara Tes','Sosialisme','parlementer','Jakarta','2026-11-27') RETURNING id");
check('Negara valid bisa dibuat (Sosialisme + parlementer)', typeof okCountry.id === 'number', `id=${okCountry.id}`);

await closeDb();
console.log(`\n[pg-test] SELESAI: ${passed} lolos, ${failed} gagal`);
process.exit(failed ? 1 : 0);
